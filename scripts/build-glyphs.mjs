// Copies the Lucide icons Krya's pages use (node_modules/lucide-static, MIT) into
// src/webview/lucide.ts: the inner markup of each 24-unit SVG, so the pages draw
// them inline with no dependency at run time. Run after adding a name below:
//   node scripts/build-glyphs.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const NAMES = [
  // actions and pages
  'volume-2', 'languages', 'graduation-cap', 'scan', 'mic', 'audio-lines', 'keyboard', 'file-text', 'notebook-pen', 'book-open', 'list-checks', 'house', 'info', 'settings',
  // the sidebar
  'list-ordered', 'message-square-text', 'arrow-left',
  // rows
  'file-audio', 'users', 'spell-check', 'video', 'cpu', 'folder', 'copy', 'external-link', 'rotate-cw', 'rotate-ccw', 'database', 'play', 'pause', 'power', 'list', 'monitor', 'clock', 'lock', 'download', 'globe', 'type', 'message-square', 'star', 'search', 'trash-2', 'circle-alert', 'circle-check', 'check', 'link', 'memory-stick', 'hard-drive', 'boxes', 'laptop', 'sparkles', 'wand-sparkles', 'thumbs-up', 'loader',
  // the tray panel (P1, 2026-10-30): an icon of its own on every row
  'pencil-line', 'monitor-speaker', 'scan-text', 'text-cursor', 'panel-bottom',
  // controls
  'plus', 'x', 'minus', 'square', 'chevron-right', 'chevron-left', 'chevron-down', 'arrow-up', 'arrow-down',
]

const here = fileURLToPath(new URL('.', import.meta.url))
const icons = {}
for (const name of NAMES) {
  const svg = readFileSync(`${here}/../node_modules/lucide-static/icons/${name}.svg`, 'utf8')
  icons[name] = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim()
}

const out = `// Generated by scripts/build-glyphs.mjs from lucide-static (Lucide, MIT): the icons
// the pages draw inline. Do not edit by hand; add a name to the script and run it.

export const LUCIDE = ${JSON.stringify(icons, null, 2)} as const

export type LucideName = keyof typeof LUCIDE

/** A Lucide icon: a 24-grid outline SVG, 20 px by default (\`.lu\`), 16 px with the \`s\` class. */
export function lucide(name: LucideName, cls = ''): SVGSVGElement {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg')
  svg.setAttribute('class', cls ? \`lu \${cls}\` : 'lu')
  svg.setAttribute('viewBox', '0 0 24 24')
  svg.setAttribute('aria-hidden', 'true')
  svg.innerHTML = LUCIDE[name]
  return svg
}
`
writeFileSync(`${here}/../src/webview/lucide.ts`, out)
console.log(`${NAMES.length} icons → src/webview/lucide.ts`)
